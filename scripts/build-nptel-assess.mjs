import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const outPath = path.join(root, "nptel-assessment.js");

function getWeekNum(filename) {
  const m = filename.match(/week\s*(\d+)/i);
  return m ? Number(m[1]) : null;
}

function extractQuestions(text, weekNum) {
  const questions = [];
  const parts = text.split(/QUESTION\s+(\d+)/i);
  for (let i = 1; i < parts.length; i += 2) {
    const qnum = Number(parts[i]);
    let block = parts[i + 1] || "";
    
    // Find correct answer
    const correctMatch = block.match(/Correct Answer:\s*([^\n\r]+)/i);
    let correctLine = correctMatch ? correctMatch[1] : "";
    
    // Everything before correct answer
    const beforeCorrect = block.split(/Correct Answer:/i)[0];
    
    // Extract question text - everything before first option
    const optionMatch = beforeCorrect.match(/[\r\n]\s*([a-dA-D])[\)\.]\s+/);
    let qText = beforeCorrect;
    if (optionMatch) {
      qText = beforeCorrect.slice(0, optionMatch.index);
    }
    
    qText = qText.replace(/^\s*[\r\n]+/, "").replace(/\s+[\r\n]+/g, "\n").trim();
    qText = qText.replace(/^State whether the following statement is True or False\.?\s*/i, "");
    qText = qText.replace(/^Statement:\s*/i, "");
    
    // Extract ALL options
    const options = [];
    const optRegex = /[\r\n]\s*([a-dA-D])[\)\.]\s+([^\r\n]+)/g;
    let m;
    while ((m = optRegex.exec(beforeCorrect))) {
      let optText = m[2].trim();
      optText = optText.replace(/\s*[-–—]\s*$/, "").trim();
      // Skip if it's part of "Correct Answer" line accidentally
      if (optText.toLowerCase().startsWith('correct answer')) continue;
      options.push(optText);
    }
    
    if (options.length === 0) continue;
    
    // Determine correct answers
    // Match standalone option letters: preceded by start/space/comma/punctuation, not embedded in words.
    // e.g. "a, b, and c" → a, b, c (ignores the 'd' and 'a' inside "and")
    const standaloneLetterRe = /(?:^|[^a-zA-Z])([a-dA-D])(?:[,\.\)\s]|$)/g;
    function extractStandaloneLetters(str) {
      const found = [];
      const seen = new Set();
      let m2;
      const re = new RegExp(standaloneLetterRe.source, "g");
      while ((m2 = re.exec(str)) !== null) {
        const letter = m2[1].toLowerCase();
        if (!seen.has(letter)) { found.push(letter); seen.add(letter); }
      }
      return found;
    }

    const correctAnswers = [];
    // Check if multiple answers (comma-separated or contains "and" between letters)
    const isMultiLine = /[a-dA-D]\s*,\s*[a-dA-D]|[a-dA-D]\s+and\s+[a-dA-D]/i.test(correctLine);
    if (isMultiLine) {
      const letters = extractStandaloneLetters(correctLine);
      const seen = new Set();
      for (const letter of letters) {
        const idx = letter.charCodeAt(0) - 97;
        if (idx >= 0 && idx < options.length && !seen.has(idx)) {
          correctAnswers.push(idx);
          seen.add(idx);
        }
      }
    } else {
      const letterMatch = correctLine.match(/^\s*([a-dA-D])[\)\.]/);
      if (letterMatch) {
        const idx = letterMatch[1].toLowerCase().charCodeAt(0) - 97;
        if (idx >= 0 && idx < options.length) {
          correctAnswers.push(idx);
        }
      } else {
        const textOnly = correctLine.replace(/^[a-dA-D][\)\.]\s*/, "").trim().toLowerCase();
        for (let i = 0; i < options.length; i++) {
          if (options[i].trim().toLowerCase() === textOnly || options[i].toLowerCase().includes(textOnly) && textOnly.length > 10) {
            correctAnswers.push(i);
            break;
          }
        }
      }
    }
    
    // Extract explanation - stop before "Why this option"
    let explanation = "";
    const expMatch = block.match(/Easy Theory\s*\/\s*Explanation:\s*([\s\S]*?)(?:\r?\n\s*Why this option|\r?\n\s*QUESTION\s+\d+|$)/i);
    if (expMatch) {
      explanation = expMatch[1].trim();
      explanation = explanation.replace(/\r\n/g, "\n").replace(/\n\s*\n+/g, "\n").trim();
    }
    
    questions.push({
      id: `nptel-w${weekNum}-q${qnum}`,
      qnum,
      q: qText,
      options,
      answer: correctAnswers.length === 1 ? correctAnswers[0] : correctAnswers,
      answers: correctAnswers,
      explanation,
      multiple: correctAnswers.length > 1
    });
  }
  return questions;
}

const files = fs.readdirSync(root).filter(f => /^week\s*\d+\.md$/i.test(f));
const assessments = [];

for (const file of files) {
  const weekNum = getWeekNum(file);
  if (!weekNum) continue;
  const content = fs.readFileSync(path.join(root, file), "utf8");
  const questions = extractQuestions(content, weekNum);
  if (questions.length === 0) continue;
  
  for (const q of questions) {
    q.id = `nptel-w${weekNum}-q${q.qnum}`;
  }
  
  assessments.push({
    week: weekNum,
    title: `NPTEL Week ${weekNum} Assessment`,
    questions
  });
}

assessments.sort((a, b) => a.week - b.week);

fs.writeFileSync(outPath, `/* Generated by scripts/build-nptel-assess.mjs */\nwindow.NPTEL_ASSESSMENT = ${JSON.stringify(assessments, null, 2)};\n`, "utf8");
console.log(`Wrote ${outPath}`);
console.log(`Weeks: ${assessments.length}, Total questions: ${assessments.reduce((n,w)=>n+w.questions.length,0)}`);
for (const a of assessments) {
  console.log(`Week ${a.week}: ${a.questions.length} questions`);
}
