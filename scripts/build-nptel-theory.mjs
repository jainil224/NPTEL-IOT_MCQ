import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const outPath = path.join(root, "nptel-theory.js");

function getWeekNum(filename) {
  const m = filename.match(/week\s*(\d+)/i);
  return m ? Number(m[1]) : null;
}

function extractTheory(text, weekNum) {
  const items = [];
  const parts = text.split(/QUESTION\s+(\d+)/i);
  
  for (let i = 1; i < parts.length; i += 2) {
    const qnum = Number(parts[i]);
    let block = parts[i + 1] || "";
    
    // Extract question text
    const beforeCorrect = block.split(/Correct Answer:/i)[0];
    const optionMatch = beforeCorrect.match(/[\r\n]\s*([a-dA-D])[\)\.]\s+/);
    let qText = beforeCorrect;
    if (optionMatch) {
      qText = beforeCorrect.slice(0, optionMatch.index);
    }
    qText = qText.replace(/^\s*[\r\n]+/, "").replace(/\s+[\r\n]+/g, " ").trim();
    qText = qText.replace(/^State whether the following statement is True or False\.?\s*/i, "");
    qText = qText.replace(/^Statement:\s*/i, "");
    
    // Extract Easy Theory / Explanation
    let theory = "";
    const expMatch = block.match(/Easy Theory\s*\/\s*Explanation:\s*([\s\S]*?)(?:\r?\n\s*Why this option|\r?\n\s*QUESTION\s+\d+|$)/i);
    if (expMatch) {
      theory = expMatch[1].trim();
      theory = theory.replace(/\r\n/g, "\n").replace(/\n\s*\n+/g, "\n").trim();
    }
    
    // Extract Why this option is correct
    let why = "";
    const whyMatch = block.match(/Why this option.*?:\s*([\s\S]*?)(?:\r?\n\s*QUESTION\s+\d+|$)/i);
    if (whyMatch) {
      why = whyMatch[1].trim();
      why = why.replace(/\r\n/g, "\n").replace(/\n\s*\n+/g, "\n").trim();
    }
    
    // Extract keywords from question
    const keywords = [];
    const keywordPatterns = [
      /Smart Dust/gi, /M2M/gi, /IoT/gi, /IPv[46]/gi, /gateway/gi, /sensor/gi, 
      /actuator/gi, /accelerometer/gi, /hysteresis/gi, /resolution/gi, /accuracy/gi,
      /address/gi, /vector/gi, /SLAAC/gi, /DHCPv6/gi, /Web of Things/gi
    ];
    for (const pattern of keywordPatterns) {
      const matches = qText.match(pattern);
      if (matches) {
        for (const m of matches) {
          if (!keywords.includes(m)) keywords.push(m);
        }
      }
    }
    
    if (theory || why) {
      items.push({
        id: `nptel-t-w${weekNum}-q${qnum}`,
        qid: `nptel-w${weekNum}-q${qnum}`,
        qnum,
        questionText: qText,
        theoryTitle: qText.length > 60 ? qText.substring(0, 57) + "..." : qText,
        theory,
        why,
        keywords
      });
    }
  }
  return items;
}

const files = fs.readdirSync(root).filter(f => /^week\s*\d+\.md$/i.test(f));
const nptelTheory = [];

for (const file of files) {
  const weekNum = getWeekNum(file);
  if (!weekNum) continue;
  const content = fs.readFileSync(path.join(root, file), "utf8");
  const items = extractTheory(content, weekNum);
  if (items.length === 0) continue;
  
  nptelTheory.push({
    week: weekNum,
    title: `NPTEL Week ${weekNum} Assessment Theory`,
    items
  });
}

nptelTheory.sort((a, b) => a.week - b.week);

fs.writeFileSync(outPath, `/* Generated by scripts/build-nptel-theory.mjs */\nwindow.NPTEL_THEORY = ${JSON.stringify(nptelTheory, null, 2)};\n`, "utf8");
console.log(`Wrote ${outPath}`);
console.log(`Weeks: ${nptelTheory.length}, Total items: ${nptelTheory.reduce((n,w)=>n+w.items.length,0)}`);
for (const a of nptelTheory) {
  console.log(`Week ${a.week}: ${a.items.length} theory items`);
}
